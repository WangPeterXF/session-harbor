#!/usr/bin/env node

import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(scriptDir, '..');
const docsDir = path.join(root, 'docs');
const checkOnly = process.argv.includes('--check');

const rawBase = 'https://raw.githubusercontent.com/WangPeterXF/session-harbor/main';
const pagesBase = 'https://wangpeterxf.github.io/session-harbor';

const sources = [
  ['README.md', 'Human overview, installation, commands, safety model, and limitations'],
  ['AGENTS.md', 'Repository guidance and code-review invariants for coding agents'],
  ['docs/agent-index.md', 'Compact machine-oriented task and source router'],
  ['plugins/session-harbor/skills/session-harbor/SKILL.md', 'Installed SessionHarbor operating workflow'],
  ['docs/architecture.md', 'Executable component architecture'],
  ['docs/threat-model.md', 'Safety invariants, expected failures, and residual risks'],
  ['docs/live-readiness-checklist.md', 'Physical-drive validation and cleanup gates'],
  ['docs/management-center.md', 'Dedicated conversational management task semantics'],
  ['PRIVACY.md', 'Local data handling and destination privacy policy'],
  ['TERMS.md', 'Noncommercial terms and user responsibilities'],
  ['SUPPORT.md', 'Safe support and evidence-reporting route']
];

function webLink(relativePath) {
  return `${rawBase}/${relativePath.split(path.sep).join('/')}`;
}

const llmsIndex = `# SessionHarbor

> Local-first, integrity-checked backup, verified local-space reclamation, restore, and reviewed cross-device continuity for Codex sessions on macOS and Windows.

SessionHarbor is an unofficial independent project by Xiaofan Wang. It is source-available for noncommercial use under PolyForm Noncommercial 1.0.0 and is not OSI open source. It never promises native Codex sidebar reconstruction. Begin operational work read-only; backup and cleanup are separate scopes.

## Start here
- [Machine-oriented agent index](${pagesBase}/agent-index.md): Task routing, install prompts, commands, safety gates, and source map.
- [Combined SessionHarbor context](${pagesBase}/llms-full.txt): Curated single-file export for agents that need the complete operating context.
- [Project website](${pagesBase}/): Human-readable product overview and install route.
- [GitHub repository](https://github.com/WangPeterXF/session-harbor): Source, issues, releases, and verification history.

## Primary documentation
${sources.map(([file, description]) => `- [${file}](${webLink(file)}): ${description}.`).join('\n')}

## Structured contracts
- [Contract v1 JSON Schema](${webLink('schemas/session-harbor-contracts-v1.schema.json')}): Portable device, snapshot, head, run, memory, and protocol records.
- [Plugin manifest](${webLink('plugins/session-harbor/.codex-plugin/plugin.json')}): Installable plugin identity and discovery metadata.
- [Discovery evaluation set](${webLink('evals/plugin-discovery.json')}): Five positive and three negative golden prompts.

## Optional
- [Frozen three-layer design](${webLink('docs/v2-architecture.md')}): Detailed architecture and invariants.
- [OpenAI plugin submission pack](${webLink('docs/openai-plugin-submission.md')}): Listing copy, test cases, URLs, and pre-submission checklist.
`;

const fullParts = await Promise.all(
  sources.map(async ([file]) => {
    const body = await readFile(path.join(root, file), 'utf8');
    return `\n\n---\n\n# Source: ${file}\n\n${body.trim()}\n`;
  })
);

const llmsFull = `# SessionHarbor combined agent context

> Generated from authoritative repository files by scripts/generate-agent-docs.mjs. Do not edit this file directly.

Canonical repository: https://github.com/WangPeterXF/session-harbor
Generated content version: repository main
${fullParts.join('')}`;

const outputs = [
  [path.join(docsDir, 'llms.txt'), `${llmsIndex.trim()}\n`],
  [path.join(docsDir, 'llms-full.txt'), `${llmsFull.trim()}\n`]
];

let drift = false;
for (const [target, expected] of outputs) {
  if (checkOnly) {
    let actual = '';
    try {
      actual = await readFile(target, 'utf8');
    } catch {
      // Missing generated files are reported as drift below.
    }
    if (actual !== expected) {
      console.error(`Generated agent document is stale: ${path.relative(root, target)}`);
      drift = true;
    }
  } else {
    await writeFile(target, expected, 'utf8');
    console.log(`Generated ${path.relative(root, target)}`);
  }
}

if (drift) {
  console.error('Run npm run docs:generate and commit the generated files.');
  process.exitCode = 1;
}
